def full_width(lines):
    out = []
    for s in lines:
        if s.startswith('\\begin{tabular}{'):
            s = '\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}' + s[len('\\begin{tabular}{'):]
        elif s == '\\end{tabular}':
            s = '\\end{tabular*}'
        out.append(s)
    return out

def write(label, lines, values):
    p = os.path.join(TEX, 'tab_%s.tex' % label)
    if label in FULL_WIDTH:
        lines = full_width(lines)
    with open(p, 'w', encoding='ascii', newline='\n') as f:
        f.write('%% generated by report/build_tables.py; never edit\n')
        f.write('\n'.join(lines) + '\n')
    OUT[label] = values
